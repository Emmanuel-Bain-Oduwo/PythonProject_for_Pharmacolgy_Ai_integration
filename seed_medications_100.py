def seed_medications():
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    cur = conn.cursor()
    inserted = 0
    skipped = 0

    for med in MEDICATIONS:
        row = {c: med.get(c) for c in COLUMNS}
        row.setdefault("is_active", 1)
        row.setdefault("who_essential", 0)

        placeholders = ", ".join(["?"] * len(COLUMNS))
        col_str = ", ".join(COLUMNS)
        values = [row[c] for c in COLUMNS]

        try:
            cur.execute(
                f"INSERT OR IGNORE INTO medications ({col_str}) VALUES ({placeholders})",
                values
            )
            if cur.rowcount > 0:
                inserted += 1
                log.info("  ✅ Inserted: %s", med["name"])
            else:
                skipped += 1
                log.debug("  ⚠️  Skipped (already exists): %s", med["name"])
        except Exception as e:
            log.error("  ❌ Error inserting %s: %s", med.get("name","?"), e)

    conn.commit()
    conn.close()
    log.info("\n📊 Done — Inserted: %d | Skipped: %d | Total medications: %d",
             inserted, skipped, len(MEDICATIONS))


if __name__ == "__main__":
    seed_medications()
